"""EXP-D1 -- apply the PhysioNet binary model to CirCor, unchanged (Phase 71).

Order of operations matters and is enforced, not merely intended:

1. Measure both populations and write ``population_mismatch.json``. It must
   contain no metric, and it is written **before** any prediction exists.
2. Load the finalized binary model, apply it to all 3,163 CirCor recordings.
   Nothing is fitted, nothing is tuned, nothing is thresholded to CirCor.
3. Score at recording level and at patient level under all three aggregation
   rules, quantify the drop against EXP-A2, and emit **T16** and **G29**.

    python scripts/22_cross_dataset.py
"""

from __future__ import annotations

import sys
from pathlib import Path

if __package__ in (None, ""):  # allow `python scripts/22_cross_dataset.py`
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from src.utils.logging_setup import get_logger

log = get_logger("cross_dataset")

SECTION = "outputs/08_circor_external_validation"
RUN_DIR = "EXP-D1"
COMMAND = "python scripts/22_cross_dataset.py"


def _write_framing_note(root: Path, metadata: dict, frame) -> Path:
    """The framing rule beside the number it applies to (T71.5)."""
    train = metadata["train"]
    test = metadata["test"]
    recording = frame[(frame["level"] == "recording")].set_index("metric")

    def cell(metric: str, column: str) -> str:
        if metric not in recording.index:
            return "n/a"
        return format(float(recording.loc[metric, column]), ".4f")

    lines = [
        "# EXP-D1: adult-to-paediatric transfer, and how to describe it",
        "",
        "Generated by `" + COMMAND + "`. Every number is measured.",
        "",
        "## What was transferred to what",
        "",
        "| | train | test |",
        "|---|---|---|",
        "| corpus | " + train["dataset"] + " | " + test["dataset"] + " |",
        "| cohort | " + train["cohort"] + " | " + test["cohort"] + " |",
        "| age | median "
        + format(float(train["age_median_years"]), ".0f")
        + " years ("
        + str(train["n_records_with_age"])
        + " of "
        + str(train["n_records_in_appendix"])
        + " records report one) | bands only: "
        + ", ".join(
            str(k) + " " + str(v)
            for k, v in sorted(test["age_band_counts"].items(), key=lambda kv: -kv[1])
        )
        + " |",
        "| under 18 | "
        + str(train["n_under_18"])
        + " records ("
        + format(float(train["share_under_18"]), ".2%")
        + ") | "
        + str(test["n_paediatric"])
        + " patients ("
        + format(float(test["share_paediatric_of_recorded"]), ".1%")
        + " of those with a band) |",
        "",
        "The two corpora do not even record age on the same scale -- PhysioNet in "
        "years, CirCor in bands -- which is itself part of the mismatch.",
        "",
        "## The result",
        "",
        "| metric | in domain (EXP-A2, 25 folds) | external (CirCor, 1 evaluation) | delta |",
        "|---|---|---|---|",
    ]
    for metric in ("sensitivity", "specificity", "balanced_accuracy", "roc_auc", "accuracy"):
        if metric not in recording.index:
            continue
        lines.append(
            "| "
            + metric.replace("_", " ")
            + " | "
            + cell(metric, "in_domain_mean")
            + " | "
            + cell(metric, "external_value")
            + " | "
            + format(float(recording.loc[metric, "delta"]), "+.4f")
            + " |"
        )

    lines += [
        "",
        "## How this must be described",
        "",
        "> " + metadata["framing_rule"],
        "",
        "Three reasons the two columns above are not like for like, all of them "
        "recorded before the numbers existed:",
        "",
        "1. **Population.** Adult degenerative disease (CAD 287, MVP 134) against "
        "a paediatric cohort in which the dominant abnormal finding is a murmur. "
        "The acoustic signature of the abnormal class is not the same object.",
        "2. **Corpus heterogeneity inside the training set.** " + metadata["second_known_cause"],
        "3. **Different questions.** PhysioNet's label is acoustic "
        "(normal/abnormal heart sound); CirCor's `Outcome` is a clinical decision "
        "about the patient. A model can hear correctly and still disagree with a "
        "referral decision.",
        "",
        "What the result **does** support: a screening model trained on adults "
        "should not be deployed on children without retraining, and this is the "
        "measurement that says so. What it does **not** support: any claim about "
        "PV-MEPCG's in-domain performance, which is EXP-A2's, or any claim that "
        "the method does not generalize.",
        "",
        "## What was NOT done",
        "",
        "No retuning of any kind. No threshold fitted to CirCor, no recalibration, "
        "no feature reselection, no partial refit. The model is byte-identical to "
        "`models_saved/binary/final/model.joblib`, fitted on "
        + str(metadata.get("model", {}).get("n_records_fitted", "?"))
        + " PhysioNet records with hyperparameters from "
        + str(metadata.get("model", {}).get("hyperparameter_source", "?"))
        + ".",
        "",
        "---",
        "",
        "*PV-MEPCG / PulseVision is an academic screening and decision-support "
        "prototype. It is not a diagnostic tool and must not be used to diagnose, "
        "treat, or make clinical decisions about any patient.*",
        "",
    ]

    path = root / "population_mismatch.md"
    path.write_text(chr(10).join(lines), encoding="utf-8")
    log.info("%s: %d line(s)", path.name, len(lines))
    return path


def main() -> int:
    from src.evaluation.transfer import (
        degradation,
        evaluate_transfer,
        read_metadata,
        transfer_predictions,
        write_population_metadata,
    )
    from src.models.registry import load_model
    from src.reporting.graphs import write_graph
    from src.reporting.tables import write_table
    from src.reporting.transfer_report import build_g29, build_t16, build_transfer_frame
    from src.utils.run_manifest import start_run

    section = Path(SECTION)
    root = section / RUN_DIR
    run = start_run("cross_dataset")
    written: dict[str, Path] = {}

    # 1. The framing, before anything is predicted. The manifest is read from
    #    the saved model rather than restated, so the file cannot describe a
    #    configuration other than the one that is about to be applied.
    _, manifest = load_model("binary", "final")
    written["population metadata"] = write_population_metadata(root, model_manifest=manifest)

    # 2. The transfer.
    predictions, used_manifest = transfer_predictions()
    if used_manifest.get("hyperparameters") != manifest.get("hyperparameters"):
        log.error("the model changed between the metadata write and the run")
        return 2
    predictions_path = root / "predictions.parquet"
    predictions.to_parquet(predictions_path, index=False)
    written["predictions"] = predictions_path

    # 3. Scoring, the drop, and the deliverables.
    external = evaluate_transfer(predictions)
    external_path = root / "metrics_by_level.csv"
    external.to_csv(external_path, index=False)
    written["metrics by level"] = external_path

    drops = degradation(external)
    frame = build_transfer_frame(external, drops)
    drop_path = root / "degradation.csv"
    frame.to_csv(drop_path, index=False)
    written["degradation"] = drop_path

    sources = (
        str(external_path).replace("\\", "/"),
        "outputs/06_binary_results/EXP-A2/per_fold_metrics.csv",
        "models_saved/binary/final/manifest.json",
    )
    table = build_t16(frame, sources, command=COMMAND)
    for fmt, path in write_table(table, section).items():
        written["T16 " + fmt] = path

    graph = build_g29(frame, sources, command=COMMAND)
    for fmt, path in write_graph(graph, formats=("png", "svg")).items():
        written["G29 " + fmt] = path

    written["framing note"] = _write_framing_note(root, read_metadata(root), frame)

    for path in written.values():
        run.record_artifact(path)
    run.set("retuning_performed", False)
    run.set("model", "models_saved/binary/final")
    run.finish(status="ok")

    print()
    recording = frame[frame["level"] == "recording"]
    print(
        recording[["metric", "in_domain_mean", "external_value", "delta"]]
        .round(4)
        .to_string(index=False)
    )
    print()
    for name, path in written.items():
        print(f"{name:26s} -> {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
